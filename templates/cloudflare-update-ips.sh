#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Cloudflare IP list updater (installed as /usr/local/sbin/cloudflare-update-ips)
# - Fetches Cloudflare's IPv4 and IPv6 ranges and validates every line
# - Writes /etc/nginx/cloudflare/real-ip.conf and edge-ips.conf, runs
#   nginx -t, and restores the previous files if Nginx rejects them
# - Reloads Nginx only when a list changed; run daily by
#   cloudflare-update-ips.timer
#
# Usage:
#   cloudflare-update-ips [--no-reload]
#
# CLOUDFLARE_IPS_SOURCE=<dir> reads <dir>/ips-v4 and <dir>/ips-v6 instead
# of fetching them (offline mirrors, tests).
# ==============================================================================

LIST_DIR=/etc/nginx/cloudflare
LOCK_FILE=/run/lock/cloudflare-update-ips.lock
SOURCE_URL=https://www.cloudflare.com
MIN_RANGES=8
FILES=(real-ip.conf edge-ips.conf)
IPV4_CIDR='^([0-9]{1,3}\.){3}[0-9]{1,3}/([0-9]|[12][0-9]|3[0-2])$'
IPV6_CIDR='^[0-9A-Fa-f:]*:[0-9A-Fa-f:]*/([0-9]|[1-9][0-9]|1[01][0-9]|12[0-8])$'

RELOAD=1
WORK_DIR=""

# Prints an error to stderr (the journal under the service) and exits 1.
die() {
  echo "cloudflare-update-ips: $*" >&2
  exit 1
}

# Removes the scratch directory on any exit.
cleanup() {
  if [[ -n $WORK_DIR ]]; then
    rm -rf "$WORK_DIR"
  fi
}

# Accepts --no-reload (the installer restarts Nginx itself).
parse_args() {
  local arg
  for arg in "$@"; do
    case $arg in
      --no-reload) RELOAD=0 ;;
      *) die "unknown argument: $arg (usage: cloudflare-update-ips [--no-reload])" ;;
    esac
  done
}

# Holds an exclusive lock, so a manual run and the timer never overlap.
take_lock() {
  mkdir -p "$(dirname "$LOCK_FILE")"
  exec 9>"$LOCK_FILE"
  flock -n 9 || die "another run holds $LOCK_FILE"
}

# Copies one family's raw list (v4 or v6) to the given file, from
# CLOUDFLARE_IPS_SOURCE when set, else from Cloudflare over HTTPS.
fetch_list() {
  local family="$1"
  local dest="$2"

  if [[ -n ${CLOUDFLARE_IPS_SOURCE:-} ]]; then
    cp "$CLOUDFLARE_IPS_SOURCE/ips-$family" "$dest" \
      || die "cannot read $CLOUDFLARE_IPS_SOURCE/ips-$family"
    return
  fi
  curl -fsS --proto '=https' --tlsv1.2 --max-time 30 \
    "$SOURCE_URL/ips-$family" -o "$dest" \
    || die "fetching $SOURCE_URL/ips-$family failed"
}

# Prints the CIDRs of a raw list, one per line. Any line that is not a
# CIDR of the family rejects the whole list, as does an empty one.
validate_list() {
  local family="$1"
  local file="$2"
  local pattern=$IPV4_CIDR line count=0

  [[ $family == v6 ]] && pattern=$IPV6_CIDR
  # || [[ -n $line ]]: the last line may lack a newline
  while IFS= read -r line || [[ -n $line ]]; do
    line=${line//$'\r'/}
    line=${line//[[:space:]]/}
    [[ -z $line ]] && continue
    [[ $line =~ $pattern ]] \
      || die "rejected ips-$family: not an IP$family CIDR: ${line:0:60}"
    echo "$line"
    count=$((count + 1))
  done <"$file"

  ((count > 0)) || die "rejected ips-$family: no ranges"
}

# Writes real-ip.conf and edge-ips.conf for the validated ranges.
build_files() {
  local ranges="$1"
  local header="# Generated by cloudflare-update-ips from Cloudflare's IP lists. Do not edit: the next run replaces it."
  local cidr

  {
    echo "$header"
    while IFS= read -r cidr; do
      echo "set_real_ip_from $cidr;"
    done <"$ranges"
    echo "real_ip_header CF-Connecting-IP;"
  } >"$WORK_DIR/real-ip.conf"

  {
    echo "$header"
    while IFS= read -r cidr; do
      echo "$cidr 1;"
    done <"$ranges"
  } >"$WORK_DIR/edge-ips.conf"
}

# True when both generated files already match the new ones.
unchanged() {
  local file
  for file in "${FILES[@]}"; do
    cmp -s "$WORK_DIR/$file" "$LIST_DIR/$file" || return 1
  done
}

# Puts the previous files back (or removes the new ones on a first run).
restore_files() {
  local file
  for file in "${FILES[@]}"; do
    if [[ -f $WORK_DIR/backup/$file ]]; then
      mv -f "$WORK_DIR/backup/$file" "$LIST_DIR/$file"
    else
      rm -f "$LIST_DIR/$file"
    fi
  done
}

# Swaps the new files in (each by rename, so Nginx never reads half a
# file), then runs nginx -t; on failure restores the previous files.
install_files() {
  local file output

  mkdir -p "$LIST_DIR" "$WORK_DIR/backup"
  for file in "${FILES[@]}"; do
    if [[ -f $LIST_DIR/$file ]]; then
      cp -p "$LIST_DIR/$file" "$WORK_DIR/backup/$file"
    fi
    install -m 0644 "$WORK_DIR/$file" "$LIST_DIR/.$file.new"
    mv -f "$LIST_DIR/.$file.new" "$LIST_DIR/$file"
  done

  if ! output=$(nginx -t 2>&1); then
    restore_files
    echo "$output" >&2
    die "nginx -t failed with the new lists; previous files restored"
  fi
}

main() {
  local family raw ranges total

  parse_args "$@"
  take_lock
  WORK_DIR=$(mktemp -d)
  trap cleanup EXIT

  ranges="$WORK_DIR/ranges"
  : >"$ranges"
  for family in v4 v6; do
    raw="$WORK_DIR/ips-$family"
    fetch_list "$family" "$raw"
    validate_list "$family" "$raw" >>"$ranges"
  done

  total=$(wc -l <"$ranges")
  ((total >= MIN_RANGES)) \
    || die "rejected lists: $total ranges, expected at least $MIN_RANGES"

  build_files "$ranges"
  if unchanged; then
    echo "Cloudflare IP lists unchanged ($total ranges)."
    return
  fi

  install_files
  echo "Cloudflare IP lists updated ($total ranges) in $LIST_DIR."

  if ((RELOAD)) && systemctl is-active --quiet nginx; then
    systemctl reload nginx
    echo "Nginx reloaded."
  fi
}

main "$@"
